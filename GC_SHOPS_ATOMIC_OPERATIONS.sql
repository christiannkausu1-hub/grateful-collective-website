-- Atomic shop operations. Run after GC_ENHANCEMENTS.sql and GC_SHOPS_UPGRADE.sql.
-- SECURITY INVOKER preserves the caller's table grants and RLS policies.
create or replace function public.gc_record_shop_sale(
 p_product_id bigint, p_quantity numeric, p_unit_price numeric, p_discount numeric,
 p_amount_paid numeric, p_payment_method text, p_sale_date date,
 p_customer_name text default null, p_customer_phone text default null, p_notes text default null,
 p_receipt_number text default null
) returns bigint language plpgsql security invoker set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_product public.gc_shop_products%rowtype; v_customer_id bigint; v_sale_id bigint;
 v_subtotal numeric(12,2); v_total numeric(12,2); v_customer_name text:=nullif(trim(p_customer_name),'');
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 if p_sale_date is null or p_sale_date>current_date or nullif(trim(p_payment_method),'') is null then raise exception 'Sale date must be today or earlier and payment method is required'; end if;
 if length(coalesce(trim(p_receipt_number),''))>80 then raise exception 'Receipt number must be 80 characters or fewer'; end if;
 if length(coalesce(p_customer_name,''))>160 or length(coalesce(p_customer_phone,''))>50 or length(coalesce(p_notes,''))>300 then raise exception 'Customer details or notes exceed the allowed length'; end if;
 if p_quantity is null or p_quantity<=0 or p_unit_price is null or p_unit_price<0 or p_discount is null or p_discount<0 or p_amount_paid is null or p_amount_paid<0 then raise exception 'Invalid sale values'; end if;
 select * into v_product from public.gc_shop_products where id=p_product_id and user_id=v_uid for update;
 if not found then raise exception 'Product not found or access denied'; end if;
 if coalesce(v_product.is_active,true)=false then raise exception 'This product is inactive and cannot be sold'; end if;
 if p_quantity>v_product.quantity then raise exception 'Insufficient stock; available quantity is %',v_product.quantity; end if;
 if p_discount<>round(p_discount,2) or p_amount_paid<>round(p_amount_paid,2) or p_unit_price<>round(p_unit_price,2) then raise exception 'Money values must have no more than two decimal places'; end if;
 v_subtotal:=round(p_quantity*p_unit_price,2); v_total:=v_subtotal-round(p_discount,2);
 if p_discount>v_subtotal or p_amount_paid>v_total then raise exception 'Discount or amount received exceeds sale total'; end if;
 if p_payment_method='Credit' and p_amount_paid<>0 then raise exception 'Credit sale initial payment must be zero; record each later payment separately'; end if;
 if p_payment_method<>'Credit' and p_amount_paid<>v_total then raise exception 'Non-credit sales must be paid in full; choose Credit for an outstanding balance'; end if;
 if coalesce(p_payment_method,'') not in ('Cash','Bank','Airtel Money','MTN MoMo','Credit','Other') then raise exception 'Invalid sale payment method'; end if;
 if upper(coalesce(p_payment_method,''))='CREDIT' and (v_customer_name is null or nullif(trim(p_customer_phone),'') is null) then raise exception 'Customer name and phone are required for credit sales'; end if;
 if upper(coalesce(p_payment_method,''))='CREDIT' and p_amount_paid>0 then raise exception 'For credit sales, record the initial payment as a separate credit payment so its actual payment channel is captured'; end if;
 if v_customer_name is not null then
  select id into v_customer_id from public.gc_shop_customers where user_id=v_uid and lower(customer_name)=lower(v_customer_name) and coalesce(regexp_replace(phone,'[^0-9]','','g'),'')=coalesce(regexp_replace(nullif(trim(p_customer_phone),''),'[^0-9]','','g'),'') order by id limit 1;
  if v_customer_id is null then insert into public.gc_shop_customers(user_id,customer_name,phone) values(v_uid,v_customer_name,nullif(trim(p_customer_phone),'')) returning id into v_customer_id; end if;
 end if;
 insert into public.gc_shop_sales(user_id,receipt_number,shop,customer_id,customer_name,customer_phone,sale_date,subtotal,discount,total,amount_paid,payment_method,status,notes,created_by)
 values(v_uid,coalesce(nullif(trim(p_receipt_number),''),'GC-'||upper(left(regexp_replace(v_product.shop,'[^A-Z]','','g'),3))||'-'||substr(md5(random()::text||clock_timestamp()::text||gen_random_uuid()::text),1,16)),v_product.shop,v_customer_id,coalesce(v_customer_name,'Walk-in customer'),nullif(trim(p_customer_phone),''),p_sale_date,v_subtotal,p_discount,v_total,p_amount_paid,p_payment_method,'COMPLETED',nullif(trim(p_notes),''),v_uid) returning id into v_sale_id;
 insert into public.gc_shop_sale_items(user_id,sale_id,product_id,product_name,quantity,unit_price,unit_cost,line_total,original_unit_price,price_override)
 values(v_uid,v_sale_id,v_product.id,v_product.product_name,p_quantity,p_unit_price,v_product.unit_cost,v_total,v_product.selling_price,p_unit_price is distinct from v_product.selling_price);
 update public.gc_shop_products set quantity=quantity-p_quantity,updated_at=now() where id=v_product.id and user_id=v_uid;
 if not found then raise exception 'Stock quantity could not be reduced'; end if;
 insert into public.gc_shop_movements(user_id,product_id,shop,movement_date,movement_type,quantity,unit_price,amount,description,sale_id,previous_quantity,resulting_quantity)
 values(v_uid,v_product.id,v_product.shop,p_sale_date,'SALE',p_quantity,p_unit_price,v_total,'Receipt '||(select receipt_number from public.gc_shop_sales where id=v_sale_id)||'; '||p_payment_method||'; discount '||p_discount,v_sale_id,v_product.quantity,v_product.quantity-p_quantity);
 if p_amount_paid>0 then
  insert into public.transactions(user_id,date,type,area,category,description,amount,method,notes)
  values(v_uid,p_sale_date,'Income','Shop',v_product.shop||' | Sales','Shop sale '||(select receipt_number from public.gc_shop_sales where id=v_sale_id)||' — '||v_product.product_name,p_amount_paid,case when p_payment_method='Credit' then 'Other' else p_payment_method end,'Shop sale total '||v_total||'; discount '||p_discount||'; amount received '||p_amount_paid);
 end if;
 return v_sale_id;
end; $$;

create or replace function public.gc_record_shop_credit_payment(
 p_sale_id bigint,p_payment_date date,p_amount numeric,p_payment_method text,p_notes text default null
) returns bigint language plpgsql security invoker set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_sale public.gc_shop_sales%rowtype; v_payment_id bigint; v_tx_id uuid; v_balance_after numeric(12,2);
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 if p_amount is null or p_amount<=0 or p_payment_date is null or p_amount<>round(p_amount,2) then raise exception 'Enter a valid payment date and amount (maximum two decimal places)'; end if;
 if coalesce(p_payment_method,'') not in ('Cash','Bank','Airtel Money','MTN MoMo','Other') then raise exception 'Invalid payment method'; end if;
 if length(coalesce(p_notes,''))>300 then raise exception 'Payment notes must be 300 characters or fewer'; end if;
 select * into v_sale from public.gc_shop_sales where id=p_sale_id and user_id=v_uid for update;
 if not found or v_sale.status<>'COMPLETED' then raise exception 'Open sale not found or access denied'; end if;
 if v_sale.payment_method<>'Credit' then raise exception 'Credit payments are only accepted for sales recorded as Credit'; end if;
 if p_payment_date<v_sale.sale_date then raise exception 'Credit payment date cannot be earlier than the sale date'; end if;
 if v_sale.customer_id is null then raise exception 'Credit sale has no linked customer record; correct the customer record before accepting payment'; end if;
 if v_sale.amount_paid>=v_sale.total then raise exception 'This sale has no outstanding credit balance'; end if;
 if p_amount>v_sale.total-v_sale.amount_paid then raise exception 'Payment exceeds outstanding balance'; end if;
 insert into public.gc_shop_customer_payments(user_id,sale_id,customer_id,payment_date,amount,payment_method,notes)
 values(v_uid,v_sale.id,v_sale.customer_id,p_payment_date,p_amount,p_payment_method,nullif(trim(p_notes),'')) returning id into v_payment_id;
 update public.gc_shop_sales set amount_paid=amount_paid+p_amount where id=v_sale.id and user_id=v_uid returning total-amount_paid into v_balance_after;
 if not found then raise exception 'Sale balance could not be updated'; end if;
 insert into public.transactions(user_id,date,type,area,category,description,amount,method,notes)
 values(v_uid,p_payment_date,'Income','Shop',v_sale.shop||' | Credit sale payment','Credit payment for '||v_sale.receipt_number||' — '||coalesce(v_sale.customer_name,'Customer'),p_amount,p_payment_method,nullif(trim(p_notes),'')) returning id into v_tx_id;
 update public.gc_shop_customer_payments set accounting_transaction_id=v_tx_id,balance_after=v_balance_after where id=v_payment_id and user_id=v_uid;
 return v_payment_id;
end; $$;

create or replace function public.gc_cancel_shop_sale(p_sale_id bigint,p_refund_date date default current_date,p_refund_method text default null,p_reason text default null)
returns boolean language plpgsql security invoker set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_sale public.gc_shop_sales%rowtype; v_item record; v_tx_id uuid; v_refund_id bigint;
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 if p_refund_date is null then raise exception 'Refund date is required'; end if;
 if nullif(trim(p_reason),'') is null or length(p_reason)>300 then raise exception 'A cancellation reason of 1–300 characters is required'; end if;
 if p_refund_method is not null and p_refund_method not in ('Cash','Bank','Airtel Money','MTN MoMo','Other') then raise exception 'Invalid refund payment method'; end if;
 select * into v_sale from public.gc_shop_sales where id=p_sale_id and user_id=v_uid for update;
 if not found or v_sale.status<>'COMPLETED' then raise exception 'Completed sale not found or already cancelled'; end if;
 if p_refund_date<v_sale.sale_date or p_refund_date<(select coalesce(max(payment_date),v_sale.sale_date) from public.gc_shop_customer_payments where sale_id=v_sale.id and user_id=v_uid) then raise exception 'Refund date cannot be earlier than the sale or its latest credit payment'; end if;
 if not exists(select 1 from public.gc_shop_sale_items where sale_id=v_sale.id and user_id=v_uid) then raise exception 'Sale has no item rows; cancellation is blocked for manual review'; end if;
 if exists(select 1 from public.gc_shop_sale_items where sale_id=v_sale.id and user_id=v_uid and product_id is null) then raise exception 'A sold product link is missing; cancellation is blocked for manual stock review'; end if;
 for v_item in select * from public.gc_shop_sale_items where sale_id=v_sale.id and user_id=v_uid loop
  if v_item.product_id is not null then
   update public.gc_shop_products set quantity=quantity+v_item.quantity,updated_at=now() where id=v_item.product_id and user_id=v_uid;
   if not found then raise exception 'Could not restore stock for product %',v_item.product_id; end if;
   update public.gc_shop_movements set movement_type='CANCELLED',description='Cancelled receipt '||v_sale.receipt_number where user_id=v_uid and product_id=v_item.product_id and movement_type='SALE' and sale_id=v_sale.id;
   if not found then
    -- One-time compatibility fallback for sales recorded before sale_id was introduced.
    update public.gc_shop_movements set movement_type='CANCELLED',sale_id=v_sale.id,description='Cancelled receipt '||v_sale.receipt_number where user_id=v_uid and product_id=v_item.product_id and movement_type='SALE' and sale_id is null and description like '%'||v_sale.receipt_number||'%';
   end if;
   if not found then raise exception 'Could not find the original stock movement for product %',v_item.product_id; end if;
  end if;
 end loop;
 update public.gc_shop_sales set status='CANCELLED',cancelled_at=now(),cancelled_by=v_uid,cancellation_reason=nullif(trim(p_reason),'') where id=v_sale.id and user_id=v_uid;
 if not found then raise exception 'Sale status could not be updated'; end if;
 -- Refund the original payment using its original channel unless an explicit refund channel was supplied.
 if v_sale.amount_paid>0 and v_sale.payment_method<>'Credit' then
  insert into public.gc_shop_refunds(user_id,sale_id,refund_date,amount,payment_method,reason,created_by)
  values(v_uid,v_sale.id,p_refund_date,v_sale.amount_paid,coalesce(p_refund_method,v_sale.payment_method),trim(p_reason),v_uid) returning id into v_refund_id;
  insert into public.transactions(user_id,date,type,area,category,description,amount,method,notes)
  values(v_uid,p_refund_date,'Expense','Shop',v_sale.shop||' | Refund','Refund for cancelled receipt '||v_sale.receipt_number,
         v_sale.amount_paid,coalesce(p_refund_method,v_sale.payment_method),'Refund ledger recorded. Reason: '||trim(p_reason)) returning id into v_tx_id;
  update public.gc_shop_refunds set accounting_transaction_id=v_tx_id where id=v_refund_id and user_id=v_uid;
 end if;
 -- Refund each later credit payment separately, retaining its original channel by default.
 for v_item in select cp.id,cp.amount,cp.payment_date,cp.payment_method from public.gc_shop_customer_payments cp where cp.sale_id=v_sale.id and cp.user_id=v_uid loop
  insert into public.gc_shop_refunds(user_id,sale_id,customer_payment_id,refund_date,amount,payment_method,reason,created_by)
  values(v_uid,v_sale.id,v_item.id,p_refund_date,v_item.amount,coalesce(p_refund_method,v_item.payment_method),trim(p_reason),v_uid) returning id into v_refund_id;
  insert into public.transactions(user_id,date,type,area,category,description,amount,method,notes)
  values(v_uid,p_refund_date,'Expense','Shop',v_sale.shop||' | Refund','Refund of credit payment for receipt '||v_sale.receipt_number,
         v_item.amount,coalesce(p_refund_method,v_item.payment_method),'Original payment date '||v_item.payment_date||'. Reason: '||trim(p_reason)) returning id into v_tx_id;
  update public.gc_shop_refunds set accounting_transaction_id=v_tx_id where id=v_refund_id and user_id=v_uid;
 end loop;
 return true;
end; $$;

