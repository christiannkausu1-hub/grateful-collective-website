-- Product creation and opening stock are committed together.
create or replace function public.gc_create_shop_product(
 p_shop text,p_product_name text,p_product_code text default null,p_barcode text default null,
 p_category text default null,p_supplier_name text default null,p_reorder_level numeric default 5,
 p_quantity numeric default 0,p_unit_cost numeric default 0,p_selling_price numeric default 0,p_opening_stock_date date default current_date
) returns bigint language plpgsql security invoker set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_id bigint;
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 if p_opening_stock_date is null or p_opening_stock_date>current_date then raise exception 'Opening stock date must be today or earlier'; end if;
 if p_shop not in ('TUCK SHOP','SALOON','GROCERY') or nullif(trim(p_product_name),'') is null or length(trim(p_product_name))>160 then raise exception 'Valid shop and product name (1–160 characters) are required'; end if;
 if coalesce(p_quantity,-1)<0 or coalesce(p_reorder_level,-1)<0 or coalesce(p_unit_cost,-1)<0 or coalesce(p_selling_price,-1)<0 then raise exception 'Quantity, reorder level, cost and price cannot be negative'; end if;
 if p_quantity<>round(p_quantity,3) or p_reorder_level<>round(p_reorder_level,3) or p_unit_cost<>round(p_unit_cost,2) or p_selling_price<>round(p_selling_price,2) then raise exception 'Use up to three decimals for quantity and two for money'; end if;
 if exists(select 1 from public.gc_shop_products where user_id=v_uid and lower(shop)=lower(p_shop) and lower(trim(product_name))=lower(trim(p_product_name))) then raise exception 'A product with this name already exists in this shop'; end if;
 if nullif(trim(p_product_code),'') is not null and exists(select 1 from public.gc_shop_products where user_id=v_uid and lower(trim(product_code))=lower(trim(p_product_code))) then raise exception 'Product code already exists'; end if;
 if nullif(trim(p_barcode),'') is not null and exists(select 1 from public.gc_shop_products where user_id=v_uid and trim(barcode)=trim(p_barcode)) then raise exception 'Barcode already exists'; end if;
 insert into public.gc_shop_products(user_id,shop,product_name,product_code,barcode,category,supplier_name,reorder_level,quantity,unit_cost,selling_price)
 values(v_uid,p_shop,trim(p_product_name),nullif(trim(p_product_code),''),nullif(trim(p_barcode),''),nullif(trim(p_category),''),nullif(trim(p_supplier_name),''),p_reorder_level,p_quantity,p_unit_cost,p_selling_price) returning id into v_id;
 if p_quantity>0 then
  insert into public.gc_shop_movements(user_id,product_id,shop,movement_date,movement_type,quantity,unit_price,amount,description,previous_quantity,resulting_quantity)
  values(v_uid,v_id,p_shop,p_opening_stock_date,'OPENING',p_quantity,p_unit_cost,round(p_quantity*p_unit_cost,2),'Opening stock brought forward',0,p_quantity);
 end if;
 return v_id;
end; $$;
revoke all on function public.gc_create_shop_product(text,text,text,text,text,text,numeric,numeric,numeric,numeric,date) from public;
grant execute on function public.gc_create_shop_product(text,text,text,text,text,text,numeric,numeric,numeric,numeric,date) to authenticated;

