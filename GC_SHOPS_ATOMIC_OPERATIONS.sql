-- Atomic stock movement: the movement and quantity change commit or roll back together.
create or replace function public.gc_record_stock_movement(
 p_product_id bigint,p_movement_date date,p_movement_type text,p_quantity numeric,
 p_unit_price numeric default 0,p_amount numeric default 0,p_description text default null
) returns bigint language plpgsql security invoker set search_path=public as $$
declare v_uid uuid:=auth.uid(); v_product public.gc_shop_products%rowtype; v_id bigint; v_next numeric(12,3);
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 if p_movement_date is null or p_movement_date>current_date or p_quantity is null or p_quantity<=0 or p_unit_price is null or p_unit_price<0 or p_amount is null or p_amount<0 then raise exception 'Invalid movement date, quantity or amount'; end if;
 if p_movement_type not in ('RESTOCK','DAMAGE','EXPIRED') then raise exception 'Use the sale form for sales; supported manual movements are RESTOCK, DAMAGE and EXPIRED'; end if;
 if p_quantity<>round(p_quantity,3) or p_unit_price<>round(p_unit_price,2) or p_amount<>round(p_amount,2) then raise exception 'Quantity supports up to three decimals and money supports up to two decimals'; end if;
 if p_amount<>round(p_quantity*p_unit_price,2) then raise exception 'Movement amount must equal quantity multiplied by unit price'; end if;
 if length(coalesce(p_description,''))>300 then raise exception 'Movement description must be 300 characters or fewer'; end if;
 select * into v_product from public.gc_shop_products where id=p_product_id and user_id=v_uid for update;
 if not found then raise exception 'Product not found or access denied'; end if;
 if p_movement_type='RESTOCK' and coalesce(v_product.is_active,true)=false then raise exception 'Archived products cannot be restocked; reactivate the product first'; end if;
 v_next:=case when p_movement_type='RESTOCK' then v_product.quantity+p_quantity else v_product.quantity-p_quantity end;
 if v_next<0 then raise exception 'Movement exceeds available stock'; end if;
 insert into public.gc_shop_movements(user_id,product_id,shop,movement_date,movement_type,quantity,unit_price,amount,description,previous_quantity,resulting_quantity)
 values(v_uid,v_product.id,v_product.shop,p_movement_date,p_movement_type,p_quantity,p_unit_price,p_amount,nullif(trim(p_description),''),v_product.quantity,v_next) returning id into v_id;
 if p_movement_type in ('RESTOCK','DAMAGE','EXPIRED') then
  update public.gc_shop_products set quantity=v_next,updated_at=now() where id=v_product.id and user_id=v_uid;
  if not found then raise exception 'Stock quantity could not be updated'; end if;
 end if;
 if p_movement_type in ('DAMAGE','EXPIRED') and p_amount>0 then
  insert into public.transactions(user_id,date,type,area,category,description,amount,method,notes)
  values(v_uid,p_movement_date,'Expense','Shop',v_product.shop||' | Stock loss',p_movement_type||' stock loss — '||v_product.product_name,p_amount,'Other',nullif(trim(p_description),''));
 end if;
 return v_id;
end; $$;
