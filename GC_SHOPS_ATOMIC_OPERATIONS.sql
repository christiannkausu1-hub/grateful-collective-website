-- Replacing the audit restore RPC makes repeat restores idempotent and never trusts
-- changed_by from an uploaded backup.
create or replace function public.gc_restore_audit_log(p_rows jsonb)
returns integer language plpgsql security definer set search_path=public,pg_temp as $$
declare v_uid uuid:=auth.uid(); r jsonb; n integer:=0; v_table text; v_record text; v_action text; v_changed timestamptz;
begin
 if v_uid is null then raise exception 'Authentication required'; end if;
 if jsonb_typeof(p_rows)<>'array' then raise exception 'Audit backup must be a JSON array'; end if;
 if jsonb_array_length(p_rows)>5000 then raise exception 'Audit restore is limited to 5,000 entries per request'; end if;
 for r in select value from jsonb_array_elements(p_rows) loop
  if (r->>'user_id')::uuid is distinct from v_uid then raise exception 'Audit entry owner mismatch'; end if;
  v_table:=nullif(trim(r->>'table_name'),''); v_record:=r->>'record_id'; v_action:=r->>'action';
  v_changed:=coalesce((r->>'changed_at')::timestamptz,now());
  if v_table is null or length(v_table)>128 or v_action is null or v_action not in ('INSERT','UPDATE','DELETE') then raise exception 'Audit entry has invalid required fields'; end if;
  if not exists(select 1 from public.gc_audit_log a where a.user_id=v_uid and a.table_name=v_table
    and a.record_id is not distinct from v_record and a.action=v_action and a.changed_at=v_changed
    and a.old_values is not distinct from r->'old_values' and a.new_values is not distinct from r->'new_values') then
   insert into public.gc_audit_log(user_id,table_name,record_id,action,old_values,new_values,changed_at,changed_by)
   values(v_uid,v_table,v_record,v_action,r->'old_values',r->'new_values',v_changed,v_uid);
   n:=n+1;
  end if;
 end loop;
 return n;
end; $$;
revoke all on function public.gc_restore_audit_log(jsonb) from public;
grant execute on function public.gc_restore_audit_log(jsonb) to authenticated;

