-- THE GRATEFUL COLLECTIVE: fixed assets register
-- Additive migration: creates only the new table and policies; it does not modify or delete existing records.
-- Run once in Supabase Dashboard -> SQL Editor. Safe to re-run.

create table if not exists public.gc_fixed_assets (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  asset_name text not null check (length(trim(asset_name)) > 0),
  category text not null,
  purchase_date date not null default current_date,
  purchase_cost numeric(14,2) not null default 0 check (purchase_cost >= 0),
  quantity integer not null default 1 check (quantity > 0),
  condition text not null default 'Good' check (condition in ('New','Good','Fair','Needs repair','Unusable')),
  location text,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.gc_fixed_assets enable row level security;

-- The app exposes this section only to administrators. Enforce that same role at the database layer.
drop policy if exists gc_fixed_assets_admin_select on public.gc_fixed_assets;
drop policy if exists gc_fixed_assets_admin_insert on public.gc_fixed_assets;
drop policy if exists gc_fixed_assets_admin_update on public.gc_fixed_assets;
drop policy if exists gc_fixed_assets_admin_delete on public.gc_fixed_assets;

create policy gc_fixed_assets_admin_select
on public.gc_fixed_assets for select to authenticated
using (
  auth.uid() = user_id
  and exists (
    select 1 from public.gc_user_roles r
    where r.user_id = auth.uid() and r.role = 'administrator'
  )
);

create policy gc_fixed_assets_admin_insert
on public.gc_fixed_assets for insert to authenticated
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.gc_user_roles r
    where r.user_id = auth.uid() and r.role = 'administrator'
  )
);

create policy gc_fixed_assets_admin_update
on public.gc_fixed_assets for update to authenticated
using (
  auth.uid() = user_id
  and exists (
    select 1 from public.gc_user_roles r
    where r.user_id = auth.uid() and r.role = 'administrator'
  )
)
with check (
  auth.uid() = user_id
  and exists (
    select 1 from public.gc_user_roles r
    where r.user_id = auth.uid() and r.role = 'administrator'
  )
);

create policy gc_fixed_assets_admin_delete
on public.gc_fixed_assets for delete to authenticated
using (
  auth.uid() = user_id
  and exists (
    select 1 from public.gc_user_roles r
    where r.user_id = auth.uid() and r.role = 'administrator'
  )
);

grant select, insert, update, delete on public.gc_fixed_assets to authenticated;
grant usage, select on sequence public.gc_fixed_assets_id_seq to authenticated;
