-- Enforce normalized customer uniqueness where existing data permits it.
-- If historical duplicates already exist, preserve them and let the UI block new duplicates.
do $$ begin
 if not exists (
  select 1 from public.gc_shop_customers
  group by user_id,lower(trim(customer_name)),coalesce(nullif(trim(phone),''),'')
  having count(*)>1
 ) then
  create unique index if not exists gc_shop_customers_user_name_phone_uidx
   on public.gc_shop_customers(user_id,lower(trim(customer_name)),coalesce(nullif(trim(phone),''),''));
 end if;
end $$;
