-- Add stock-loss movement types while preserving existing SALE/RESTOCK/EXPENSE history.
do $$ declare d text; begin
 -- Remove only the original autogenerated three-value constraint from GC_ENHANCEMENTS.sql.
 -- Preserve every custom check constraint on this table.
 select pg_get_constraintdef(oid) into d from pg_constraint
  where conrelid='public.gc_shop_movements'::regclass and conname='gc_shop_movements_movement_type_check' and contype='c';
 if d is not null and d ilike '%movement_type%' and d ilike '%SALE%' and d ilike '%RESTOCK%' and d ilike '%EXPENSE%' and d not ilike '%DAMAGE%' then
  alter table public.gc_shop_movements drop constraint gc_shop_movements_movement_type_check;
 end if;
 if not exists (select 1 from pg_constraint where conrelid='public.gc_shop_movements'::regclass and conname='gc_shop_movements_type_check') then
  alter table public.gc_shop_movements add constraint gc_shop_movements_type_check
   check (movement_type in ('SALE','RESTOCK','EXPENSE','DAMAGE','EXPIRED','ADJUSTMENT','REFUND','CANCELLED'));
 end if;
end $$;

create table if not exists public.gc_shop_customers (
 id bigint generated by default as identity primary key,
 user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 customer_name text not null, phone text, notes text,
 created_at timestamptz not null default now()
);
create table if not exists public.gc_shop_sales (
 id bigint generated by default as identity primary key,
 user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 receipt_number text not null, shop text not null check(shop in ('TUCK SHOP','SALOON','GROCERY')),
 customer_id bigint references public.gc_shop_customers(id) on delete set null,
 customer_name text, customer_phone text, sale_date date not null default current_date,
 subtotal numeric(12,2) not null default 0 check(subtotal>=0), discount numeric(12,2) not null default 0 check(discount>=0),
 total numeric(12,2) not null default 0 check(total>=0), amount_paid numeric(12,2) not null default 0 check(amount_paid>=0),
 payment_method text not null default 'Cash', status text not null default 'COMPLETED' check(status in ('COMPLETED','REFUNDED','CANCELLED')),
 notes text, created_at timestamptz not null default now(), unique(user_id,receipt_number)
);
create table if not exists public.gc_shop_sale_items (
 id bigint generated by default as identity primary key,
 user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 sale_id bigint not null references public.gc_shop_sales(id) on delete cascade,
 product_id bigint references public.gc_shop_products(id) on delete set null,
 product_name text not null, quantity numeric(12,3) not null check(quantity>0),
 unit_price numeric(12,2) not null check(unit_price>=0), unit_cost numeric(12,2) not null default 0 check(unit_cost>=0),
 line_total numeric(12,2) not null check(line_total>=0), created_at timestamptz not null default now()
);
create table if not exists public.gc_shop_customer_payments (
 id bigint generated by default as identity primary key,
 user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
 sale_id bigint not null references public.gc_shop_sales(id) on delete cascade,
 customer_id bigint references public.gc_shop_customers(id) on delete set null,
 payment_date date not null default current_date, amount numeric(12,2) not null check(amount>0),
 payment_method text not null default 'Cash', notes text, created_at timestamptz not null default now()
);

