-- Enable RLS and isolate every new table by authenticated user.
do $$ declare t text; begin foreach t in array array['gc_transfers','gc_reconciliation','gc_shop_products','gc_shop_movements'] loop
 execute format('alter table public.%I enable row level security',t);
 execute format('drop policy if exists %I on public.%I',t||'_own_all',t);
 execute format('create policy %I on public.%I for all using (auth.uid()=user_id) with check (auth.uid()=user_id)',t||'_own_all',t);
 end loop; end $$;
