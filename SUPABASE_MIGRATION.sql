-- THE GRATEFUL COLLECTIVE additive migration. Safe to run more than once; does not drop existing records/tables.
create table if not exists public.gc_audit_log (
 id bigint generated by default as identity primary key, user_id uuid not null default auth.uid(), table_name text not null,
 record_id text, action text not null check (action in ('INSERT','UPDATE','DELETE')), old_values jsonb, new_values jsonb,
 changed_at timestamptz not null default now(), changed_by uuid default auth.uid()
);
alter table public.gc_audit_log enable row level security;
drop policy if exists gc_audit_read_own on public.gc_audit_log;
create policy gc_audit_read_own on public.gc_audit_log for select using (auth.uid() = user_id);
-- Trigger writes are security-definer so a deleted row can still be audited; users can only read their own log.
create or replace function public.gc_capture_audit() returns trigger language plpgsql security definer set search_path=public as $$
declare oldj jsonb; newj jsonb; owner_id uuid; rid text;
begin
 oldj := case when TG_OP='INSERT' then null else to_jsonb(OLD) end;
 newj := case when TG_OP='DELETE' then null else to_jsonb(NEW) end;
 owner_id := coalesce((newj->>'user_id')::uuid,(oldj->>'user_id')::uuid,auth.uid());
 rid := coalesce(newj->>'id',oldj->>'id');
 insert into public.gc_audit_log(user_id,table_name,record_id,action,old_values,new_values,changed_by)
 values(owner_id,TG_TABLE_NAME,rid,TG_OP,oldj,newj,auth.uid());
 if TG_OP='DELETE' then return OLD; else return NEW; end if;
end; $$;
do $$ declare t text; begin
 foreach t in array array['transactions','rental_units','rental_payments','suppliers','trade_payables','trade_payable_payments','workers','payroll_records','pupils','lunch_payments','school_tests','test_payments'] loop
  if to_regclass('public.'||t) is not null then
   execute format('drop trigger if exists gc_audit_trigger on public.%I',t);
   execute format('create trigger gc_audit_trigger after insert or update or delete on public.%I for each row execute function public.gc_capture_audit()',t);
  end if;
 end loop;
end $$;
